// Terminal colour schemes made from the palette: Terminal.app, Ghostty and iTerm2.
// Only files and profiles this app made are ever written: a user's own "APOD" stays theirs.
import AppKit
import Foundation

/// The palette as a terminal needs it.
public struct TerminalScheme: Equatable, Sendable {
    public var background, foreground, bold, cursor, cursorText, selection, selectionText: PaletteColour
    /// The 16 ANSI colours: black, red, green, yellow, blue, magenta, cyan, white, then their bright versions.
    public var ansi: [PaletteColour]

    public init(_ p: Palette) {
        let light = p.mode == .light
        background = p["background"]
        foreground = p["foreground"]
        bold = p["bright_foreground"]
        cursor = p["accent"]
        cursorText = p["background"]
        selection = p["selection"]
        selectionText = p["bright_foreground"]
        // Black and white are the background's own tints, so they read as "dim" and "bright"
        // in either mode; their bright versions sit one step further out.
        let black = light ? p["bright_foreground"] : p["lighter_background"]
        let brightBlack = p["muted"]
        let white = light ? p["lighter_background"] : p["light_foreground"]
        let brightWhite = light ? p["dark_background"] : p["bright_foreground"]
        ansi = [black, p["red"], p["green"], p["yellow"], p["blue"], p["magenta"], p["cyan"], white,
                brightBlack, p["bright_red"], p["bright_green"], p["bright_yellow"], p["bright_blue"],
                p["bright_magenta"], p["bright_cyan"], brightWhite]
    }
}

public let generatedHeader = "Generated by APOD for macOS from NASA's Astronomy Picture of the Day."

public struct TerminalThemes: Sendable {
    public var home: URL
    /// Whether to tell running terminals to reload; off in tests.
    public var reload: Bool

    public init(home: URL = FileManager.default.homeDirectoryForCurrentUser, reload: Bool = true) {
        self.home = home
        self.reload = reload
    }

    // MARK: Ghostty

    var ghosttyDirs: [URL] {
        [home.appendingPathComponent(".config/ghostty"),
         home.appendingPathComponent("Library/Application Support/com.mitchellh.ghostty")]
    }
    public var ghosttyInstalled: Bool { ghosttyDirs.contains { FileManager.default.fileExists(atPath: $0.path) } }
    public var ghosttyTheme: URL { home.appendingPathComponent(".config/ghostty/themes/apod") }

    public static func ghostty(_ s: TerminalScheme, title: String) -> String {
        var lines = ["# \(generatedHeader)"]
        if !title.isEmpty { lines.append("# " + title.split(whereSeparator: \.isWhitespace).joined(separator: " ")) }
        lines.append("# Rewritten with every new picture; edits here do not last.")
        lines += s.ansi.enumerated().map { "palette = \($0.offset)=\($0.element.hex)" }
        lines += [
            "background = \(s.background.hex)",
            "foreground = \(s.foreground.hex)",
            "cursor-color = \(s.cursor.hex)",
            "cursor-text = \(s.cursorText.hex)",
            "selection-background = \(s.selection.hex)",
            "selection-foreground = \(s.selectionText.hex)",
            "",
        ]
        return lines.joined(separator: "\n")
    }

    // MARK: iTerm2

    public var itermInstalled: Bool {
        FileManager.default.fileExists(atPath: home.appendingPathComponent("Library/Application Support/iTerm2").path)
    }
    public var itermProfile: URL { home.appendingPathComponent("Library/Application Support/iTerm2/DynamicProfiles/apod.json") }
    static let itermGuid = "io.github.smolamsk.apod-mac"

    public static func iterm(_ s: TerminalScheme) throws -> Data {
        func colour(_ c: PaletteColour) -> [String: Any] {
            let (r, g, b) = c.components
            return ["Red Component": r, "Green Component": g, "Blue Component": b, "Alpha Component": 1, "Color Space": "sRGB"]
        }
        var profile: [String: Any] = [
            "Name": "APOD",
            "Guid": itermGuid,
            "Background Color": colour(s.background),
            "Foreground Color": colour(s.foreground),
            "Bold Color": colour(s.bold),
            "Cursor Color": colour(s.cursor),
            "Cursor Text Color": colour(s.cursorText),
            "Selection Color": colour(s.selection),
            "Selected Text Color": colour(s.selectionText),
        ]
        for (i, c) in s.ansi.enumerated() { profile["Ansi \(i) Color"] = colour(c) }
        return try JSONSerialization.data(withJSONObject: ["Profiles": [profile]], options: [.prettyPrinted, .sortedKeys])
    }

    // MARK: Terminal.app

    public static let terminalProfile = "APOD"
    static let terminalBundle = "com.apple.Terminal"
    /// Terminal keeps the keys of an imported profile, so this marks the profile as ours.
    static let terminalMarker = "APODGenerated"
    static let terminalANSIKeys = ["ANSIBlackColor", "ANSIRedColor", "ANSIGreenColor", "ANSIYellowColor", "ANSIBlueColor",
                                   "ANSIMagentaColor", "ANSICyanColor", "ANSIWhiteColor", "ANSIBrightBlackColor",
                                   "ANSIBrightRedColor", "ANSIBrightGreenColor", "ANSIBrightYellowColor",
                                   "ANSIBrightBlueColor", "ANSIBrightMagentaColor", "ANSIBrightCyanColor",
                                   "ANSIBrightWhiteColor"]

    /// The .terminal file to import (once) with the popover's "Add to Terminal" button.
    public var terminalFile: URL { home.appendingPathComponent("Library/Application Support/APOD/APOD.terminal") }

    static func archived(_ c: PaletteColour) throws -> Data {
        let (r, g, b) = c.components
        return try NSKeyedArchiver.archivedData(withRootObject: NSColor(srgbRed: r, green: g, blue: b, alpha: 1),
                                                requiringSecureCoding: true)
    }

    /// The colour keys of the Terminal profile.
    public static func terminalColours(_ s: TerminalScheme) throws -> [String: Any] {
        var d: [String: Any] = [
            "BackgroundColor": try archived(s.background),
            "TextColor": try archived(s.foreground),
            "TextBoldColor": try archived(s.bold),
            "CursorColor": try archived(s.cursor),
            "SelectionColor": try archived(s.selection),
        ]
        for (key, c) in zip(terminalANSIKeys, s.ansi) { d[key] = try archived(c) }
        return d
    }

    public static func terminalFileData(_ s: TerminalScheme) throws -> Data {
        var d = try terminalColours(s)
        d["name"] = terminalProfile
        d["type"] = "Window Settings"
        d["ProfileCurrentVersion"] = 2.07
        d[terminalMarker] = true
        return try PropertyListSerialization.data(fromPropertyList: d, format: .xml, options: 0)
    }

    public var terminalRunning: Bool {
        !NSRunningApplication.runningApplications(withBundleIdentifier: Self.terminalBundle).isEmpty
    }

    /// Whether Terminal has our APOD profile; nil if Terminal has one of that name that we didn't make.
    public var terminalProfileInstalled: Bool? {
        guard let all = CFPreferencesCopyAppValue("Window Settings" as CFString, Self.terminalBundle as CFString) as? [String: Any],
              let ours = all[Self.terminalProfile] as? [String: Any] else { return false }
        return ours[Self.terminalMarker] as? Bool == true ? true : nil
    }

    /// Rewrite the colours of Terminal's APOD profile in its preferences. Only while Terminal
    /// isn't running: it keeps its profiles in memory and writes them back when it quits.
    @discardableResult
    public func updateTerminalPreferences(_ s: TerminalScheme) throws -> Bool {
        guard !terminalRunning, terminalProfileInstalled == true,
              var all = CFPreferencesCopyAppValue("Window Settings" as CFString, Self.terminalBundle as CFString) as? [String: Any],
              var ours = all[Self.terminalProfile] as? [String: Any] else { return false }
        ours.merge(try Self.terminalColours(s)) { $1 }
        all[Self.terminalProfile] = ours
        CFPreferencesSetAppValue("Window Settings" as CFString, all as CFDictionary, Self.terminalBundle as CFString)
        return CFPreferencesAppSynchronize(Self.terminalBundle as CFString)
    }

    /// The AppleScript that recolours the APOD profile in a running Terminal. Terminal's
    /// scripting can't set the ANSI colours; those follow when it quits (updateTerminalPreferences).
    public static func terminalScript(_ s: TerminalScheme) -> String {
        func rgb(_ c: PaletteColour) -> String { "{\(c.red * 257), \(c.green * 257), \(c.blue * 257)}" }
        return """
        tell application "Terminal"
            if not (exists settings set "\(terminalProfile)") then return
            set s to settings set "\(terminalProfile)"
            set background color of s to \(rgb(s.background))
            set normal text color of s to \(rgb(s.foreground))
            set bold text color of s to \(rgb(s.bold))
            set cursor color of s to \(rgb(s.cursor))
        end tell
        """
    }

    // MARK: kitty

    var kittyDir: URL { home.appendingPathComponent(".config/kitty") }
    public var kittyInstalled: Bool {
        FileManager.default.fileExists(atPath: "/Applications/kitty.app") || FileManager.default.fileExists(atPath: kittyDir.path)
    }
    /// The file kitty.conf includes and `kitten themes` writes. Unlike the other terminals'
    /// files, it isn't ours to begin with: the user opts in, and the original is kept.
    public var kittyTheme: URL { kittyDir.appendingPathComponent("current-theme.conf") }
    public var kittyBackup: URL { kittyDir.appendingPathComponent("current-theme.conf.before-apod") }
    static let kittyBundle = "net.kovidgoyal.kitty"

    public static func kitty(_ s: TerminalScheme, palette p: Palette, title: String) -> String {
        var lines = ["# \(generatedHeader)"]
        if !title.isEmpty { lines.append("# " + title.split(whereSeparator: \.isWhitespace).joined(separator: " ")) }
        lines.append("# Rewritten with every new picture; edits here do not last.")
        lines.append("# Your previous theme is in current-theme.conf.before-apod.")
        lines += [
            "",
            "foreground \(s.foreground.hex)",
            "background \(s.background.hex)",
            "selection_foreground \(s.selectionText.hex)",
            "selection_background \(s.selection.hex)",
            "cursor \(s.cursor.hex)",
            "cursor_text_color \(s.cursorText.hex)",
            "url_color \(p["accent"].hex)",
            "",
            "active_border_color \(p["accent"].hex)",
            "inactive_border_color \(p["muted"].hex)",
            "bell_border_color \(p["yellow"].hex)",
            "",
            "active_tab_foreground \(p["background"].hex)",
            "active_tab_background \(p["accent"].hex)",
            "inactive_tab_foreground \(p["foreground"].hex)",
            "inactive_tab_background \(p["lighter_background"].hex)",
            "tab_bar_background \(p["dark_background"].hex)",
            "",
        ]
        lines += s.ansi.enumerated().map { "color\($0.offset) \($0.element.hex)" }
        lines.append("")
        return lines.joined(separator: "\n")
    }

    func kittyThemeIsOurs() -> Bool {
        guard let text = try? String(contentsOf: kittyTheme, encoding: .utf8) else { return false }
        return text.contains(generatedHeader)
    }

    /// Before the first write: keep the user's theme as the backup (once, so it is never lost).
    func adoptKittyTheme(report: Reporter) throws {
        let fm = FileManager.default
        if fm.fileExists(atPath: kittyTheme.path) && !kittyThemeIsOurs() && !fm.fileExists(atPath: kittyBackup.path) {
            try fm.moveItem(at: kittyTheme, to: kittyBackup)
        }
        let conf = (try? String(contentsOf: kittyDir.appendingPathComponent("kitty.conf"), encoding: .utf8)) ?? ""
        let includes = conf.split(separator: "\n").contains {
            $0.trimmingCharacters(in: .whitespaces).range(of: #"^include\s+current-theme\.conf\s*$"#, options: .regularExpression) != nil
        }
        if !includes { report.warning("add the line `include current-theme.conf` to kitty.conf to use the APOD colours in kitty") }
    }

    /// Turning kitty off: bring back the theme from before APOD.
    public func restoreKittyTheme() {
        guard kittyThemeIsOurs() else { return }
        let fm = FileManager.default
        try? fm.removeItem(at: kittyTheme)
        if fm.fileExists(atPath: kittyBackup.path) { try? fm.moveItem(at: kittyBackup, to: kittyTheme) }
        reloadKitty()
    }

    /// kitty rereads kitty.conf, and what it includes, on SIGUSR1: every window changes at once.
    func reloadKitty() {
        guard reload else { return }
        for app in NSRunningApplication.runningApplications(withBundleIdentifier: Self.kittyBundle) {
            kill(app.processIdentifier, SIGUSR1)
        }
    }

    // MARK: Writing

    /// Write an owned file: missing, or carrying our marker. Never someone else's.
    func writeOwned(_ data: Data, to url: URL, marker: String) throws -> Bool {
        if let old = try? Data(contentsOf: url), !String(decoding: old, as: UTF8.self).contains(marker) { return false }
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try data.write(to: url, options: [.atomic])
        return true
    }

    /// Bring every enabled terminal up to date with the palette.
    public func write(_ p: Palette, title: String, settings: Settings, report: Reporter) {
        let s = TerminalScheme(p)
        if settings.ghostty && ghosttyInstalled {
            do {
                if try !writeOwned(Data(Self.ghostty(s, title: title).utf8), to: ghosttyTheme, marker: generatedHeader) {
                    report.warning("\(ghosttyTheme.path) is a theme this app didn't make; leaving it alone")
                }
            } catch { report.warning("couldn't write the Ghostty theme") }
        }
        if settings.iterm && itermInstalled {
            do {
                if try !writeOwned(Self.iterm(s), to: itermProfile, marker: Self.itermGuid) {
                    report.warning("\(itermProfile.path) is a profile this app didn't make; leaving it alone")
                }
            } catch { report.warning("couldn't write the iTerm2 profile") }
        }
        if settings.kitty && kittyInstalled {
            do {
                try adoptKittyTheme(report: report)
                try FileManager.default.createDirectory(at: kittyDir, withIntermediateDirectories: true)
                try Data(Self.kitty(s, palette: p, title: title).utf8).write(to: kittyTheme, options: [.atomic])
                reloadKitty()
            } catch { report.warning("couldn't write the kitty theme") }
        }
        if settings.terminalApp {
            do {
                try FileManager.default.createDirectory(at: terminalFile.deletingLastPathComponent(), withIntermediateDirectories: true)
                try Self.terminalFileData(s).write(to: terminalFile, options: [.atomic])
                if terminalRunning {
                    if terminalProfileInstalled == true { runScript(Self.terminalScript(s), report: report) }
                } else {
                    try updateTerminalPreferences(s)
                }
            } catch { report.warning("couldn't write the Terminal profile") }
        }
    }

    func runScript(_ source: String, report: Reporter) {
        // NSAppleScript belongs on the main thread.
        let failed = Thread.isMainThread ? Self.execute(source) : DispatchQueue.main.sync { Self.execute(source) }
        if failed { report.warning("couldn't recolour Terminal; allow APOD to control Terminal in System Settings → Privacy & Security → Automation") }
    }

    static func execute(_ source: String) -> Bool {
        var error: NSDictionary?
        NSAppleScript(source: source)?.executeAndReturnError(&error)
        return error != nil
    }
}
